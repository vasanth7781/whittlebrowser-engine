// Refreshes lib/disposable-domains.mjs from the community-maintained list at
// https://github.com/disposable-email-domains/disposable-email-domains (CC0, public domain).
// Run: pnpm --filter @whittlebrowser/website update:disposable   then commit the result.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const SOURCE = 'https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main/disposable_email_blocklist.conf';
const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`could not fetch the list: HTTP ${res.status}`);
const domains = [...new Set((await res.text()).split('\n').map((l) => l.trim().toLowerCase()).filter((l) => l && !l.startsWith('#')))].sort();
// A bad download must never block everybody, so refuse a list that is tiny or contains a mainstream mail provider.
const mainstream = ['gmail.com', 'outlook.com', 'hotmail.com', 'yahoo.com', 'icloud.com', 'proton.me', 'protonmail.com'];
if (domains.length < 1000 || mainstream.some((d) => domains.includes(d))) throw new Error(`list looks wrong (${domains.length} domains); not writing`);

const out = `// GENERATED by scripts/update-disposable.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
// Source: ${SOURCE.replace('/main/disposable_email_blocklist.conf', '')} (CC0 1.0, public domain).
// ${domains.length} domains of temporary / disposable email services.
export const DISPOSABLE_DOMAINS = ${JSON.stringify(domains.join('\n'))}.split('\\n');
`;
writeFileSync(join(import.meta.dirname, '..', 'lib', 'disposable-domains.mjs'), out);
console.log(`wrote ${domains.length} domains`);
